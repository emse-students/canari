/**
 * THE SAME GATE, AS AN NGINX CONFIGURATION - for MiConnect, whose pages authentik writes, so no
 * SvelteKit hook can stand in front of them. A small nginx in MiConnect's own compose project
 * (`infrastructure/authentik/compose.yml`, service `gate`) answers a Meta in-app browser's page
 * request with `interstitial.html` and proxies everything else to authentik unchanged.
 *
 * GENERATED, NEVER EDITED: `generate.ts` writes `infrastructure/authentik/leave-in-app-browser/`
 * from this file, `detect.ts`'s rules and `gate.ts`'s exemptions and CSP, and `make
 * test-ci-scripts` fails when the committed files differ from what it would write. One definition,
 * two spellings, no drift.
 */
import { META_IN_APP_BROWSER_RULES } from './detect';
import { GATE_EXEMPT_PREFIXES, interstitialCsp } from './gate';

/** The port the gate listens on inside its container. */
export const GATE_PORT = 8080;

/** authentik's own listener, on the compose network. */
export const AUTHENTIK_UPSTREAM = 'server:9000';

/** A regex literal for an nginx `map` key: `~` + the pattern, quoted. */
function mapRegex(pattern: string): string {
  if (!/^[A-Za-z0-9_/ |[\].^-]+$/.test(pattern)) {
    throw new Error(`a pattern outside the JS/PCRE common subset: ${pattern}`);
  }
  return `"~${pattern}"`;
}

/** A path prefix as a regex anchored at the start of `$uri`. */
function prefixRegex(prefix: string): string {
  return '^' + prefix.replaceAll('.', '\\.');
}

/** The whole `nginx.conf` of the gate, generated from `html` (the interstitial's exact bytes). */
export function renderGateConf(html: string): string {
  const apps = META_IN_APP_BROWSER_RULES.map(
    ([app, pattern]) => `        ${mapRegex(pattern)} ${app};`
  ).join('\n');
  const exempt = GATE_EXEMPT_PREFIXES.map((prefix) => `        "~${prefixRegex(prefix)}" 1;`).join(
    '\n'
  );
  return `# GENERATED by libs/leave-in-app-browser/generate.ts - DO NOT EDIT. Regenerate with
#   bun libs/leave-in-app-browser/generate.ts
# and \`make test-ci-scripts\` fails when this file differs from what it would write.
#
# MiConnect's gate (owner decision of 2026-11-25): a page request from the browser built into
# Messenger, Facebook, Instagram or Threads is answered with the interstitial; every other request
# goes to authentik unchanged. Canari's docs/wiki/frontend/leaving-in-app-browsers.md.
worker_processes 1;
error_log stderr warn;
pid /var/run/nginx.pid;

events {
    worker_connections 1024;
}

http {
    server_tokens off;
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    # authentik writes its own access log; this one records the interstitials only - the population
    # the readings are measured against (app and path's first segment, never the URL or a query).
    log_format leave_iab '$time_iso8601 [leave-iab] interstitial served site=miconnect app=$leave_iab_app route=$leave_iab_route';
    access_log /dev/stdout leave_iab if=$leave_iab_gate;

    # WHICH META APP, by detect.ts's ordered rules: nginx tries regexes in the order written, as
    # detect.ts does.
    map $http_user_agent $leave_iab_app {
        default "";
${apps}
    }
    # A TOP-LEVEL PAGE REQUEST (gate.ts, isTopLevelDocument): Sec-Fetch-Dest says so when sent,
    # else an Accept that asks for HTML.
    map $http_accept $leave_iab_accepts_html {
        default 0;
        "~text/html" 1;
    }
    map "$http_sec_fetch_dest:$leave_iab_accepts_html" $leave_iab_document {
        default 0;
        "~^document:" 1;
        "~^:1$" 1;
    }
    # gate.ts, GATE_EXEMPT_PREFIXES.
    map $uri $leave_iab_exempt {
        default 0;
${exempt}
    }
    map "$leave_iab_app:$request_method:$leave_iab_document:$leave_iab_exempt" $leave_iab_gate {
        default 0;
        "~^[a-z]+:(GET|HEAD):1:0$" 1;
    }
    map $uri $leave_iab_route {
        default "/";
        "~^/(?<first>[^/]*)" "/$first";
    }
    # WebSocket upgrades pass through (authentik's /ws/).
    map $http_upgrade $leave_iab_connection {
        default upgrade;
        "" "";
    }

    # authentik's address is RESOLVED PER REQUEST from Docker's DNS: the release recreates \`server\`
    # (deploy-stack.sh, --no-deps), which gives it a new address, and an upstream resolved once at
    # start would answer 502 after every release.
    resolver 127.0.0.11 ipv6=off valid=10s;

    server {
        listen ${GATE_PORT};
        # The host's nginx already bounds the body and the headers; this hop adds no limit of its own.
        client_max_body_size 0;
        large_client_header_buffers 8 64k;

        location / {
            error_page 418 = @leave_in_app_browser;
            if ($leave_iab_gate) {
                return 418;
            }
            set $leave_iab_upstream ${AUTHENTIK_UPSTREAM};
            proxy_pass http://$leave_iab_upstream;
            proxy_http_version 1.1;
            # Every other header - X-Forwarded-For, X-Forwarded-Proto, X-Real-IP from the host's
            # nginx - passes through as received: authentik sees what it saw before this hop existed.
            proxy_set_header Host $http_host;
            proxy_set_header Upgrade $http_upgrade;
            proxy_set_header Connection $leave_iab_connection;
            proxy_request_buffering off;
            proxy_buffer_size 64k;
            proxy_buffers 16 64k;
            proxy_busy_buffers_size 128k;
            proxy_read_timeout 3600s;
            proxy_send_timeout 3600s;
        }

        location @leave_in_app_browser {
            root /etc/nginx/leave-in-app-browser;
            try_files /interstitial.html =500;
            default_type text/html;
            charset utf-8;
            etag off;
            if_modified_since off;
            add_header Content-Security-Policy "${interstitialCsp(html)}" always;
            add_header Cache-Control "no-store" always;
            add_header Vary "User-Agent" always;
            add_header X-Robots-Tag "noindex, nofollow" always;
            add_header X-Content-Type-Options "nosniff" always;
            add_header Referrer-Policy "no-referrer" always;
        }
    }
}
`;
}
