import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * The WebView dies with the activity that owns it, and this is what says so.
 *
 * A navigation-mode switch (gestural <-> 3-button) or a System WebView update changes the app's
 * asset paths (`Config changes=80000000`, `ActivityInfo.CONFIG_ASSETS_PATHS`, a hidden bit no
 * manifest `configChanges` can name), so Android relaunches the activity in the same process. wry
 * builds a new WebView for the new activity and never destroys the old one. MEASURED ON A Mi 9T
 * 2026-10-14 on `1.2.7-alpha.1`: one more detached but LIVE page per switch, still holding its Web
 * Locks - which kept three refused salon texts away from the visible page
 * (`a live sibling tab owns them`). `MainActivity.onDestroy` destroys it.
 *
 * Nothing about this is visible at compile time, and `gen/android` is regenerated by
 * `tauri android init` and by a major Tauri upgrade - the same trap `androidBackNavigation.test.ts`
 * exists for.
 */
const here = dirname(fileURLToPath(import.meta.url));
const ANDROID_JAVA = resolve(
  here,
  '../../../src-tauri/gen/android/app/src/main/java/fr/emse/canari'
);

const mainActivity = readFileSync(resolve(ANDROID_JAVA, 'MainActivity.kt'), 'utf8');
const wryActivity = readFileSync(resolve(ANDROID_JAVA, 'generated/WryActivity.kt'), 'utf8');

/** The body of `MainActivity.onDestroy`, up to the class's closing brace. */
function onDestroyBody(): string {
  const start = mainActivity.search(/override\s+fun\s+onDestroy\s*\(\s*\)/);
  expect(start).toBeGreaterThan(-1);
  return mainActivity.slice(start);
}

describe('the Android WebView does not outlive its activity', () => {
  it('MainActivity.onDestroy destroys the WebView it was handed', () => {
    const body = onDestroyBody();
    expect(body).toMatch(/super\.onDestroy\(\)/);
    expect(body).toMatch(/webView\.destroy\(\)/);
  });

  it('runs after wry has seen the destruction, and detaches the view before destroying it', () => {
    const body = onDestroyBody();
    const superAt = body.indexOf('super.onDestroy()');
    const removeAt = body.indexOf('removeView(webView)');
    const destroyAt = body.indexOf('webView.destroy()');
    expect(superAt).toBeGreaterThan(-1);
    expect(removeAt).toBeGreaterThan(superAt);
    expect(destroyAt).toBeGreaterThan(removeAt);
  });

  it('holds the WebView it destroys from the only hook that is handed it', () => {
    expect(mainActivity).toMatch(
      /override\s+fun\s+onWebViewCreate[\s\S]{0,800}liveWebView\s*=\s*webView/
    );
  });

  it('and wry still leaves the old WebView alive, which is the reason this override exists', () => {
    // The day a Tauri upgrade destroys the WebView itself, this fails: delete the override then
    // rather than destroying twice.
    expect(wryActivity).toMatch(/override\s+fun\s+onDestroy\s*\(\s*\)/);
    expect(wryActivity).not.toMatch(/mWebView\.destroy\(\)/);
  });
});
