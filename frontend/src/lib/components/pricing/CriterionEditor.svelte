<script lang="ts">
  import { Plus, Trash2, X } from '@lucide/svelte';
  import Select from '$lib/components/ui/Select.svelte';
  import { CONTROL_HINT_CLASS, controlClass } from '$lib/components/ui/controlClasses';
  import type { Bucket, Dimension } from '$lib/pricing/priceMatrix';
  import { isPromoYear } from '$lib/pricing/criteriaOptions';
  import {
    addBucketValue,
    bucketValues,
    remainingValues,
    removeBucketValue,
    type CriterionSources,
    type CriterionValue,
  } from '$lib/pricing/bucketValues';
  import { criterionTitle } from '$lib/pricing/criterionTitle';
  import { Log } from '$lib/utils/Log';
  import { m } from '$lib/paraglide/messages';

  /**
   * One criterion of the pricing grid, as compact rows: one line per group - its name, its values as
   * chips, and a "+" that offers the values no group holds yet.
   *
   * A criterion is a PARTITION, not a filter - which is why "Tous les autres" closes the list as one
   * muted line. It is generated by the server and cannot be edited, and showing it is what makes the
   * grid legible: a manager can see that everybody has a price without counting.
   *
   * The "+" offers only what is left because the server refuses two groups that overlap; offering a
   * value already placed would only teach the manager that refusal at save time.
   */
  interface Props {
    dimension: Dimension;
    /** Where this criterion sits in the price table: "Lignes" or "Colonnes". */
    axisLabel: string;
    /** Cotisation tiers, formations and questions the values are drawn from. */
    sources: CriterionSources;
    onAddBucket: (bucket: Bucket) => void;
    onRemoveBucket: (bucketId: string) => void;
    onRemove: () => void;
    onChange: () => void;
  }

  let { dimension, axisLabel, sources, onAddBucket, onRemoveBucket, onRemove, onChange }: Props =
    $props();

  const title = $derived(criterionTitle(dimension.kind));
  const remaining = $derived(remainingValues(dimension, sources));

  /** Only questions offering options can divide anybody. */
  const questionOptions = $derived(
    sources.items
      .filter((i) => (i.options?.length ?? 0) > 0)
      .map((i) => ({ value: i.id, label: i.label || m.form_criterion_untitled_question() }))
  );

  /** The group whose "+" is open; one at a time, so the list reads as one line per group. */
  let suggestingFor = $state<string | null>(null);
  /** An older promo being typed - the "+" offers only the most recent ones. */
  let typedYear = $state('');

  function addValue(bucket: Bucket, value: CriterionValue['value']) {
    Log.d('PRICE_GRID', `add a value to group ${bucket.id} of ${dimension.kind}`);
    addBucketValue(dimension, bucket, value);
    onChange();
  }

  function removeValue(bucket: Bucket, value: CriterionValue['value']) {
    Log.d('PRICE_GRID', `remove a value from group ${bucket.id} of ${dimension.kind}`);
    removeBucketValue(dimension, bucket, value);
    onChange();
  }

  /** A typed year is added only when it is a real promo no group holds yet. */
  function addTypedYear(bucket: Bucket) {
    const year = Number(typedYear.trim());
    const placed = dimension.buckets.some((b) => (b.values ?? []).includes(year));
    if (!isPromoYear(year) || placed) {
      Log.d('PRICE_GRID', `typed promo refused: not a promo, or already placed`);
      return;
    }
    addValue(bucket, year);
    typedYear = '';
  }

  /** A new group is named at once, so the grid never shows a header with nothing in it. */
  function addGroup() {
    Log.d('PRICE_GRID', `add a group to ${dimension.kind}`);
    const bucket: Bucket = {
      id: `b${Math.random().toString(36).slice(2, 8)}`,
      label: m.form_criterion_group_default_name({ n: dimension.buckets.length + 1 }),
      ...(dimension.kind === 'cotisation' ? { anyTier: false, variantKeys: [] } : { values: [] }),
    };
    onAddBucket(bucket);
    suggestingFor = bucket.id;
  }
</script>

<div class="border-cn-border/70 rounded-2xl border p-3" data-testid="criterion-{dimension.id}">
  <div class="flex items-center gap-2">
    <span class="bg-cn-bg text-text-muted rounded-full px-2 py-0.5 text-xs font-bold">
      {axisLabel}
    </span>
    <span class="text-text-main min-w-0 flex-1 truncate text-sm font-bold">{title}</span>
    <button
      type="button"
      onclick={onRemove}
      aria-label={m.form_criterion_remove_named({ name: title })}
      title={m.form_criterion_remove_named({ name: title })}
      class="ui-icon-button text-text-muted hover:bg-red-err/10 hover:text-red-err rounded-lg transition-colors"
    >
      <Trash2 size={16} />
    </button>
  </div>

  {#if dimension.kind === 'answer'}
    <div class="mt-2">
      <Select
        label={m.form_criterion_question_label()}
        value={dimension.questionId ?? ''}
        options={[
          { value: '', label: m.form_criterion_question_placeholder() },
          ...questionOptions,
        ]}
        onValueChange={(v) => {
          Log.d('PRICE_GRID', `answer criterion now reads question ${v || '(none)'}`);
          dimension.questionId = v || undefined;
          // The options of the previous question mean nothing under the new one.
          for (const b of dimension.buckets) b.values = [];
          onChange();
        }}
      />
      <p class={CONTROL_HINT_CLASS}>{m.form_criterion_answer_hint()}</p>
    </div>
  {/if}

  <ul class="divide-cn-border/50 mt-2 divide-y">
    {#each dimension.buckets as bucket (bucket.id)}
      {@const values = bucketValues(dimension, bucket, sources)}
      <li class="flex items-start gap-2 py-1.5" data-testid="group-row">
        <input
          bind:value={bucket.label}
          oninput={onChange}
          aria-label={m.form_criterion_group_name_label()}
          class="group-name text-text-main w-28 shrink-0 bg-transparent px-1 text-sm font-bold"
          class:group-name-missing={!bucket.label.trim()}
        />
        <div class="flex min-w-0 flex-1 flex-wrap items-center gap-1.5">
          {#each values as v (String(v.value))}
            <span
              class="bg-cn-bg text-text-main inline-flex items-center gap-1 rounded-full py-0.5 pr-1 pl-2.5 text-xs font-bold"
            >
              {v.label}
              <button
                type="button"
                onclick={() => removeValue(bucket, v.value)}
                aria-label={m.form_criterion_remove_value({ value: v.label })}
                class="tap-target text-text-muted hover:text-red-err flex h-5 w-5 items-center justify-center rounded-full"
              >
                <X size={12} />
              </button>
            </span>
          {/each}
          <button
            type="button"
            onclick={() => (suggestingFor = suggestingFor === bucket.id ? null : bucket.id)}
            aria-expanded={suggestingFor === bucket.id}
            aria-label={m.form_criterion_add_value({ group: bucket.label })}
            class="tap-target border-cn-border text-text-main hover:bg-cn-bg flex h-7 w-7 items-center justify-center rounded-full border border-dashed"
          >
            <Plus size={14} />
          </button>
          {#if suggestingFor === bucket.id}
            {#each remaining as v (String(v.value))}
              <button
                type="button"
                onclick={() => addValue(bucket, v.value)}
                class="tap-target border-cn-border text-text-main hover:bg-cn-bg rounded-full border px-2.5 py-0.5 text-xs font-semibold"
              >
                + {v.label}
              </button>
            {/each}
            {#if dimension.kind === 'promo'}
              <span class="w-28">
                <input
                  bind:value={typedYear}
                  inputmode="numeric"
                  placeholder={m.form_criterion_other_year()}
                  aria-label={m.form_criterion_other_year()}
                  onkeydown={(e) => {
                    // Enter adds the year; without this it submits the form the grid sits in.
                    if (e.key === 'Enter') {
                      e.preventDefault();
                      addTypedYear(bucket);
                    }
                  }}
                  class={controlClass(false, 'compact')}
                />
              </span>
            {:else if dimension.kind === 'answer' && !dimension.questionId}
              <!-- Nothing to offer because no question is chosen yet - not because all is placed. -->
              <span class="text-text-muted text-xs">{m.form_criterion_no_options()}</span>
            {:else if remaining.length === 0}
              <span class="text-text-muted text-xs">{m.form_criterion_all_placed()}</span>
            {/if}
          {/if}
        </div>
        <button
          type="button"
          onclick={() => onRemoveBucket(bucket.id)}
          aria-label={m.form_criterion_group_remove()}
          title={m.form_criterion_group_remove()}
          class="ui-icon-button text-text-muted hover:bg-red-err/10 hover:text-red-err shrink-0 rounded-lg transition-colors"
        >
          <X size={14} />
        </button>
      </li>
    {/each}
    <!-- Generated by the server, shown because it is what makes the grid a partition: everybody who
         is in none of the groups above is in this one, and therefore has a price. -->
    <li class="text-text-muted flex items-center gap-2 py-1.5 text-sm">
      <span class="w-28 shrink-0 px-1 font-bold">{m.form_criterion_others()}</span>
      <span class="min-w-0 flex-1 text-xs">{m.form_criterion_others_hint()}</span>
      <button
        type="button"
        onclick={addGroup}
        class="tap-target border-cn-border text-text-main hover:bg-cn-bg inline-flex shrink-0 items-center gap-1 rounded-full border px-3 py-1 text-xs font-bold"
      >
        <Plus size={13} />
        {m.form_criterion_add_group_short()}
      </button>
    </li>
  </ul>
</div>

<style>
  /* An underlined name, not a boxed field: a group line stays one line high. */
  .group-name {
    min-height: 2.25rem;
    border: 0;
    border-bottom: 1px solid var(--cn-border);
  }

  .group-name:focus {
    outline: none;
    border-bottom-color: var(--text-main);
  }

  .group-name-missing {
    border-bottom-color: var(--red-err);
  }
</style>
