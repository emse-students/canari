/**
 * The generated markdown section of docs/wiki/test-suite-reform.md, from the inventory object.
 * Kept apart from `inventory.mjs` so the wording of the report and the collection of the facts change
 * independently.
 */

const fmt = (n) => n.toLocaleString('en-US');
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (p) => `\`${p}\``;

/** @param {any} inv the inventory object `inventory.mjs` builds */
export function renderMarkdown(inv) {
  const m = inv.meta;
  const t = inv.totals;
  const L = [];
  const cmd = ['bun tools/test-inventory/inventory.mjs --write-wiki'];
  if (m.timingsFiles) cmd.push('--timings <vitest --reporter=json report>');
  if (m.ciRedRuns) cmd.push(`--ci-red ${m.ciRedRuns}`);
  L.push(
    `Generated by \`${cmd.join(' ')}\` on ${m.date}, commit \`${m.commit}\`, git window since ${m.windowSince} (${m.windowDays} days). Do not edit by hand: re-run the command.`
  );
  L.push('');
  L.push(
    `**Totals.** ${fmt(t.files)} test files; ${fmt(t.cases)} cases and assertions counted statically (${fmt(t.dynamicCaseDecls)} \`it.each\` / \`test.each\` declarations, each counted once, expand to more at run time).${t.runCases == null ? '' : ` The vitest report of the same tree ran **${fmt(t.runCases)}** frontend cases, ${fmt(t.runFailed)} of them red on the machine that produced it (a local run; CI is the verdict).`} ${fmt(t.sourceTextFiles)} frontend files read app source as text (${fmt(t.sourceTextCases)} cases); ${fmt(t.purposeUnknown)} files have neither a docblock nor describe names, so their purpose is \`unknown\`; ${fmt(t.bornInFix)} files were first added by a commit whose subject says fix or revert (written for a defect that really happened).`
  );
  L.push('');
  L.push(
    `| Suite | Runner | Files | Cases (static) | Cases (run) | Skipped / ignored | Time (s) | Born in a fix | Fix-touched in window |`
  );
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const s of inv.suites) {
    L.push(
      `| ${s.label} | ${s.runner} | ${fmt(s.files)} | ${fmt(s.cases)}${s.caseUnit === 'cases' ? '' : ` ${s.caseUnit}`} | ${s.runCases == null ? '-' : fmt(s.runCases)} | ${s.skipped + s.ignored} | ${s.ms == null ? '-' : (s.ms / 1000).toFixed(1)} | ${s.bornInFix} | ${s.filesWithFix} |`
    );
  }
  L.push('');
  L.push(
    '"Time" is the sum of per-file times as the runner reports them, which run in parallel: it is a cost ranking, not the wall clock of the job. "Fix-touched" counts files touched in the window by a commit whose subject says fix, revert, regression or flake, ignoring any commit that touches more than 25 test files: **evidence that something was wrong near the test, not proof it was red**. "Born in a fix" is the stronger signal and the one a deletion review should respect first. `tools/test-inventory/README.md` says what each column can and cannot know.'
  );
  L.push('');
  if (m.ciRed) {
    L.push(
      `**Red in CI.** The last ${m.ciRed.runs} failed \`ci.yml\` runs were read (\`gh run view --log-failed\`): ${m.ciRed.withNamedTest} of them name at least one test file as failing, ${m.ciRed.logsUnavailable} had no retrievable log, the rest name no test file (a build, an audit, a lint or type check, or a runner whose log shape the scan does not read). ${t.ciRedFiles} test files were named; they carry their run and date in the JSON (\`ciRed\`).${m.ciRed.biggestRun ? ` One run, ${m.ciRed.biggestRun.run}, names ${m.ciRed.biggestRun.files} of them at once: a shared cause, not ${m.ciRed.biggestRun.files} independent reds.` : ''} Every other test is \`never red in the window\` as far as CI shows.`
    );
    L.push('');
  }
  L.push(
    `**The top 20 costly suites** (${m.timingsFiles ? 'by the runner report. It is one local run on a loaded machine, so it ranks cost but disagrees with the CI numbers of section 2.4 - re-run on a quiet one before acting on a row' : 'by case count: no timings report was given'}).`
  );
  L.push('');
  L.push(`| # | File | ${m.timingsFiles ? 'ms | ' : ''}Cases | Guards (derived, one line) |`);
  L.push(`| --- | --- | ${m.timingsFiles ? '--- | ' : ''}--- | --- |`);
  inv.top20.forEach((e, i) =>
    L.push(
      `| ${i + 1} | ${code(e.path)} | ${m.timingsFiles ? `${fmt(e.ms ?? 0)} | ` : ''}${fmt(e.runCases ?? e.cases)} | ${cell(e.purpose)} |`
    )
  );
  L.push('');
  const c = inv.candidates;
  L.push(
    `**Deletion candidates.** ${c.counts.total} flags: ${Object.entries(c.counts.byClass)
      .map(([k, v]) => `${v} \`${k}\``)
      .join(
        ', '
      )}. ${c.t5KeepFiles} source-text files are on the WP-T5 keep list or in a family it keeps whole and are not flagged. A flag is a pointer for a reviewer, never a verdict, and **nothing was deleted**. The full set, with examples, is in the JSON.`
  );
  L.push('');
  L.push('| Class | Test | Cases | Covering test | Confidence | Why flagged |');
  L.push('| --- | --- | --- | --- | --- | --- |');
  for (const x of c.listed) {
    L.push(
      `| ${x.class} | ${code(x.path)} | ${x.cases} | ${x.covering.length ? x.covering.map(code).join(', ') : 'none named'} | ${x.confidence} | ${cell(x.note)} |`
    );
  }
  L.push('');
  if (c.copies.length > 0) {
    L.push(
      `**Not deletions, but a finding: tests that repeat a counterpart in another package.** ${c.copies.length} test files are word for word a counterpart's and are not declared copies (${[...new Set(c.copies.map((x) => x.path.split('/').pop()))].join(', ')}). Each guards ITS OWN copy of the code, so deleting one leaves a copy unguarded; the duplication is the code's, not the test's.`
    );
    L.push('');
  }
  if (c.hollow > 0) {
    L.push(
      `**Cases with no assertion.** ${fmt(c.hollow)} cases in ${c.hollowFiles} files contain no \`expect\`, \`assert\` or \`should\` call (\`no-assertion\` above, listed in the JSON). Most are helper-driven or assert by not throwing; each is worth one look, because a case that cannot fail guards nothing.`
    );
    L.push('');
  }
  return L.join('\n');
}
